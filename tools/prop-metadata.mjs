// Regenerate worker-safe prop metadata after exporting assets: node tools/prop-metadata.mjs
// (tools/compress-assets.mjs runs it before compressing). Every prop root of the prop
// libraries, with its glTF extras and bounds, and PROP_FILES: which files hold each prop set
// (the game loads a set's files when a cube shows it, render/props.js).
import { readdirSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { readGlb, rootBounds, roots, BOUNDS } from './glb.mjs';

// the prop libraries (relative to assets/), in catalog order: within a set, placement draws
// from its props in this order (render/propplace.js)
export function propLibraries(directory) {
  const sets = dir => readdirSync(resolve(directory, dir)).filter(f => f.endsWith('.glb')).sort().map(f => `${dir}/${f}`);
  return [...sets('props'), ...sets('clutter'), ...sets('themes'), 'items/treasure_chest.glb', 'town.glb', 'town_trees.glb', 'town_clutter.glb', 'town_homes.glb', 'town_walls.glb', 'trials.glb'];
}

// { metadata: [{ name, set, base, ...extras, height, minY, maxY, bounds }], files: { set: [file] } }
export function propCatalog(directory) {
  const metadata = [], files = {};
  for (const file of propLibraries(directory)) {
    const { json } = readGlb(resolve(directory, file));
    for (const i of roots(json)) {
      const root = json.nodes[i], b = rootBounds(json, i);
      if (!b) continue;
      const { [BOUNDS]: _, ...extras } = root.extras ?? {};
      const [set, ...rest] = root.name.split('_');
      metadata.push({ name: root.name, set, base: rest.slice(0, -1).join('_'),
        ...extras, height: b.max[1], minY: b.min[1], maxY: b.max[1], bounds: [b.min[0], b.min[2], b.max[0], b.max[2]] });
      if (!(files[set] ??= []).includes(file)) files[set].push(file);
    }
  }
  return { metadata, files };
}
export const assetMetadata = directory => propCatalog(directory).metadata;

export function writePropMetadata(directory, out = resolve(import.meta.dirname, '../src/core/propmetadata.js')) {
  const { metadata, files } = propCatalog(directory);
  writeFileSync(out, '// Generated by tools/prop-metadata.mjs; do not edit by hand.\n'
    + '// set -> the files (in assets/) its props are in\n'
    + 'export const PROP_FILES = {\n' + Object.entries(files).map(([set, list]) => `  ${set}: ${JSON.stringify(list)}`).join(',\n') + '\n};\n'
    + 'export const PROP_METADATA = [\n' + metadata.map(p => '  ' + JSON.stringify(p)).join(',\n') + '\n];\n');
  return metadata;
}

if (process.argv[1] === import.meta.filename) {
  const metadata = writePropMetadata(resolve(import.meta.dirname, '../assets'));
  console.log('Generated metadata for', metadata.length, 'models');
}
