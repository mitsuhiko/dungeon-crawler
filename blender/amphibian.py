"""Export the local Qualmos prototype from the authored .blend.
Blender -b --python blender/amphibian.py -- [source.blend] [output.glb]
Input must have the 14 Boss* concept actions. Joins parts into one skinned mesh
with <=12 material primitives, as render/enemymodel.js requires.
"""
from pathlib import Path
import math, sys, json
import bpy
from mathutils import Vector

ROOT=Path(__file__).resolve().parents[1]
args=sys.argv[sys.argv.index('--')+1:] if '--' in sys.argv else []
source=Path(args[0]).resolve() if args else ROOT/'blender/amphibian.blend'
output=Path(args[1]).resolve() if len(args)>1 else ROOT/'assets/amphibian.glb'
preview=Path(args[2]).resolve() if len(args)>2 else None
bpy.ops.wm.open_mainfile(filepath=str(source))
rig=bpy.data.objects['BOSS RIG | Select to view actions']
rig.animation_data.action=None
for t in rig.animation_data.nla_tracks:t.mute=True
bpy.context.scene.frame_set(1)
for p in rig.pose.bones:
    p.location=(0,0,0);p.rotation_euler=(0,0,0);p.scale=(1,1,1)
bpy.context.view_layer.update()
# A death clip rather than reusing an attack as the death pose.
action=bpy.data.actions.new('BossDeath');action.use_fake_user=True
rig.animation_data.action=action
for f in range(1,77):
    t=(f-1)/75;u=min(1,t/.75);u=u*u*(3-2*u)
    for p in rig.pose.bones:
        p.location=(0,0,0);p.rotation_euler=(0,0,0);p.scale=(1,1,1)
    rig.pose.bones['body'].rotation_euler.x=.6*u
    rig.pose.bones['head'].rotation_euler.x=.4*u
    rig.pose.bones['body'].location.y=-.6*u
    for side,s in [('L',1),('R',-1)]:rig.pose.bones['arm.'+side].rotation_euler.z=s*.3*u
    for p in rig.pose.bones:
        p.keyframe_insert('location',frame=f,group=p.name)
        p.keyframe_insert('rotation_euler',frame=f,group=p.name)
        p.keyframe_insert('scale',frame=f,group=p.name)
rig.animation_data.action=None
for p in rig.pose.bones:
    p.location=(0,0,0);p.rotation_euler=(0,0,0);p.scale=(1,1,1)
bpy.context.view_layer.update()
# A real two-handed choking grab: reach, lift, two squeezes, then a downward slam.
# Bake IK, and export the actual hands' sampled path for the held player to follow.
old=bpy.data.actions.get('BossGrab')
if old:bpy.data.actions.remove(old)
grab=bpy.data.actions.new('BossGrab');grab.use_fake_user=True
rig.animation_data.action=grab
targets=[]
for side in ['L','R']:
    target=bpy.data.objects.new('GrabTarget.'+side,None);bpy.context.collection.objects.link(target)
    ik=rig.pose.bones['forearm.'+side].constraints.new('IK');ik.target=target;ik.chain_count=2;ik.use_stretch=True
    rig.pose.bones['arm.'+side].ik_stretch=.7;rig.pose.bones['forearm.'+side].ik_stretch=.7
    targets.append(target)
def ease(t):
    t=max(0,min(1,t));return t*t*(3-2*t)
for f in range(1,104):
    t=(f-1)/30
    reach=ease(t/.9);lift=ease((t-.9)/.45);slam=ease((t-2.4)/.3);recover=ease((t-2.7)/.7)
    for p in rig.pose.bones:
        p.location=(0,0,0);p.rotation_euler=(0,0,0);p.scale=(1,1,1)
    rig.pose.bones['body'].rotation_euler.x=-.10*reach+.27*slam*(1-recover)
    rig.pose.bones['head'].rotation_euler.x=.12*lift-.2*slam
    for i,side in enumerate(['L','R']):
        s=-1 if side=='L' else 1
        rest=rig.data.bones['hand.'+side].head_local.copy()
        catch=Vector((s*.17,-1.3,3.0));high=Vector((s*.14,-.95,4.2));down=Vector((s*.18,-1.4,1.9))
        at=rest.lerp(catch,reach).lerp(high,lift).lerp(down,slam).lerp(rest,recover)
        if 1.35<t<2.4:at.x+=s*.035*math.sin(t*22)
        targets[i].location=at;targets[i].keyframe_insert('location',frame=f)
    for p in rig.pose.bones:
        p.keyframe_insert('location',frame=f,group=p.name)
        p.keyframe_insert('rotation_euler',frame=f,group=p.name)
        p.keyframe_insert('scale',frame=f,group=p.name)
bpy.ops.object.select_all(action='DESELECT');rig.select_set(True);bpy.context.view_layer.objects.active=rig
bpy.ops.object.mode_set(mode='POSE');bpy.ops.pose.select_all(action='SELECT')
bpy.ops.nla.bake(frame_start=1,frame_end=103,step=1,only_selected=True,visual_keying=True,
    clear_constraints=True,use_current_action=True,bake_types={'POSE'})
bpy.ops.object.mode_set(mode='OBJECT')
path=[]
for f in range(28,83,2):
    bpy.context.scene.frame_set(f);bpy.context.view_layer.update()
    at=rig.matrix_world@((rig.pose.bones['hand.L'].head+rig.pose.bones['hand.R'].head)*.5)
    path.append([round(at.x*.65,5),round(at.z*.65,5),round(-at.y*.65,5)])
spec=dict(throwAt=2.7,step=2/30,hold=.85,throw=3.8,bites=[1.5,2.1],bitePower=.22,choke=True,grip=path)
grab['hit_frame']=27;grab['throw_frame']=81;grab['grip']=path;grab['bites']=[1.5,2.1]
grabfile=ROOT/'src/core/qualmos-grip.js' if output==ROOT/'assets/amphibian.glb' else output.with_suffix('.grip.js')
grabfile.write_text('// Generated by blender/amphibian.py: actual hand positions in world units.\nexport const QUALMOS_GRAB = '+json.dumps(spec,separators=(',',':'))+';\n',encoding='utf-8')
for target in targets:bpy.data.objects.remove(target,do_unlink=True)
rig.animation_data.action=None
bpy.context.scene.frame_set(1)
for p in rig.pose.bones:
    p.location=(0,0,0);p.rotation_euler=(0,0,0);p.scale=(1,1,1)
bpy.context.view_layer.update()
# Join at the rest pose; leave one armature modifier, preserving all vertex groups.
meshes=[o for o in bpy.data.collections['BOSS | Amphibious creature concept'].objects if o.type=='MESH']
bpy.ops.object.select_all(action='DESELECT')
for o in meshes:o.select_set(True)
bpy.context.view_layer.objects.active=meshes[0]
bpy.ops.object.join()
body=bpy.context.object;body.name='QualmosBody'
# Decimate before skinning for a responsive prototype, not a production retopology.
mod=body.modifiers.new('Prototype mesh reduction','DECIMATE');mod.ratio=.12
bpy.ops.object.modifier_move_up(modifier=mod.name)
bpy.ops.object.modifier_apply(modifier=mod.name)
body.parent=rig
rig.name='QualmosRig'
assert len(body.data.materials)<=12,len(body.data.materials)
bpy.ops.object.select_all(action='DESELECT');body.select_set(True);rig.select_set(True)
bpy.context.view_layer.objects.active=rig
for a in bpy.data.actions:
    if a.name.startswith('Boss'):a.use_fake_user=True
bpy.data.actions['BossWalk']['speed']=1.7
bpy.ops.export_scene.gltf(filepath=str(output),export_format='GLB',use_selection=True,
    export_animations=True,export_animation_mode='ACTIONS',export_force_sampling=True,
    export_frame_range=False,export_extras=True,export_cameras=False,export_lights=False,
    export_texcoords=False)
print('QUALMOS_EXPORTED',output,len(body.data.vertices),'vertices',len(body.data.materials),'materials')
if preview:
    preview.parent.mkdir(parents=True,exist_ok=True)
    rig.animation_data.action=bpy.data.actions['BossGrab'];bpy.context.scene.frame_set(58)
    scene=bpy.context.scene;scene.render.engine='CYCLES';scene.cycles.samples=16
    scene.render.resolution_x=640;scene.render.resolution_y=640;scene.render.resolution_percentage=100
    scene.render.image_settings.file_format='PNG';scene.render.filepath=str(preview)
    bpy.ops.render.render(write_still=True)
